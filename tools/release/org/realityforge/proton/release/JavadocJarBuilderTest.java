package org.realityforge.proton.release;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;
import java.util.jar.JarOutputStream;

public final class JavadocJarBuilderTest {
    private JavadocJarBuilderTest() {}

    public static void main(final String[] args) throws Exception {
        final Path root = Files.createTempDirectory("javadoc-jar-builder-test");
        try {
            final Path sources = root.resolve("sources.jar");
            try (JarOutputStream out = new JarOutputStream(Files.newOutputStream(sources))) {
                out.putNextEntry(new JarEntry("com/example/Sample.java"));
                out.write("package com.example; /** Sample documentation. */ public final class Sample {}\n"
                        .getBytes(StandardCharsets.UTF_8));
                out.closeEntry();
            }

            final Path first = root.resolve("first.jar");
            final Path second = root.resolve("second.jar");
            JavadocJarBuilder.main(new String[] {"--source-jar", sources.toString(), "--output", first.toString()});
            JavadocJarBuilder.main(new String[] {"--source-jar", sources.toString(), "--output", second.toString()});

            if (Files.mismatch(first, second) != -1) {
                throw new AssertionError("Identical inputs must produce identical Javadoc jars");
            }
            try (JarFile jar = new JarFile(first.toFile())) {
                if (jar.getJarEntry(JarFile.MANIFEST_NAME) == null) {
                    throw new AssertionError("Missing Javadoc jar manifest");
                }
                for (final JarEntry entry : jar.stream().toList()) {
                    if (entry.getTime() != 0L) {
                        throw new AssertionError("Unstable timestamp for " + entry.getName() + ": " + entry.getTime());
                    }
                }
                final var entry = jar.getJarEntry("com/example/Sample.html");
                if (entry == null) {
                    throw new AssertionError("Missing Sample documentation");
                }
                final var html = new String(jar.getInputStream(entry).readAllBytes(), StandardCharsets.UTF_8);
                if (!html.contains("Sample documentation.")) {
                    throw new AssertionError("Missing documentation content");
                }
                if (html.contains("name=\"dc.created\"")
                        || html.lines()
                                .anyMatch(line -> line.contains("Generated by javadoc") && line.contains(" on "))) {
                    throw new AssertionError("Javadoc must not embed its generation date");
                }
            }
        } finally {
            try (var paths = Files.walk(root)) {
                for (final Path path : paths.sorted(Comparator.reverseOrder()).toList()) {
                    Files.deleteIfExists(path);
                }
            }
        }
    }
}
